/**
 * Cadenas de interfaz bajo un prefijo, sin el prefijo: `tPrefijo('es', 'bio.ui.')`
 * → { copiar: 'Copiar', … }. Lo usan las calculadoras de Bioestadística abierta
 * para embarcar solo las claves de interfaz que el navegador necesita.
 */
export function tPrefijo(lang, prefix) {
  const table = UI[lang] || UI.es;
  const out = {};
  for (const k of Object.keys(UI.es)) {
    if (k.startsWith(prefix)) out[k.slice(prefix.length)] = table[k] ?? UI.es[k];
  }
  return out;
}

/** Traduce una clave de interfaz; admite interpolación {var}. */
export function t(lang, key, vars) {
  const table = UI[lang] || UI.es;
  let s = table[key];
  if (s == null) s = UI.es[key];
  if (s == null) return key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}
